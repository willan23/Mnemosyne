import {build} from 'esbuild';
import {fileURLToPath} from 'node:url';
import {writeFile} from 'node:fs/promises';

// Um único parser para o bootstrap clássico, a SPA e os testes.
const frontend = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  stdin: {contents: "import {ingestClipFromLocation} from './src/utils/clipCapture'; ingestClipFromLocation(); window.__mnemosyneClipIngressReady = true;", resolveDir: frontend, loader: 'ts'},
  bundle: true, format: 'iife', platform: 'browser', target: 'es2022', minify: true,
  write: false, logLevel: 'silent',
});
await writeFile(new URL('../public/clip-ingress.js', import.meta.url), '// Generated by scripts/build-clip-ingress.mjs; edit src/utils/clipCapture.ts.\n' + result.outputFiles[0].text);
